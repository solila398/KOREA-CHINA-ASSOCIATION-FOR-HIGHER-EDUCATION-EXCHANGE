  /* ---------------- 存储 ---------------- */
  function save(lang) {
    try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) { /* 忽略隐私模式等异常 */ }
  }
  function load() {
    try { return localStorage.getItem(STORAGE_KEY); } catch (e) { return null; }
  }

  /* ---------------- 文本翻译 ---------------- */
  function walkTextNodes(root, fn) {
    var walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode: function (node) {
        var p = node.parentNode;
        if (!p || p.nodeType !== 1) return NodeFilter.FILTER_SKIP;
        var tag = p.tagName;
        if (tag === 'SCRIPT' || tag === 'STYLE' || tag === 'NOSCRIPT') return NodeFilter.FILTER_REJECT;
        if (p.id === 'lang-toggle') return NodeFilter.FILTER_REJECT;
        if (p.closest && p.closest('.org-card')) return NodeFilter.FILTER_REJECT; /* 组织架构卡片已是双语 */
        return NodeFilter.FILTER_ACCEPT;
      }
    });
    while (walker.nextNode()) fn(walker.currentNode);
  }

  function toKorean(root) {
    walkTextNodes(root, function (node) {
      var text = node.textContent;
      var trimmed = text.trim();
      if (!trimmed || !Object.prototype.hasOwnProperty.call(dict, trimmed)) return;
      if (typeof node.__origText !== 'string') node.__origText = text;
      var start = text.indexOf(trimmed);
      node.textContent = text.slice(0, start) + dict[trimmed] + text.slice(start + trimmed.length);
    });
  }

  function toChinese(root) {
    walkTextNodes(root, function (node) {
      if (typeof node.__origText === 'string') node.textContent = node.__origText;
    });
  }

  /* ---------------- 属性（alt / title）翻译 ---------------- */
  var ATTRS = ['alt', 'title'];

  function toKoreanAttrs(root) {
    var els = root.querySelectorAll('[alt],[title]');
    Array.prototype.forEach.call(els, function (el) {
      ATTRS.forEach(function (attr) {
        if (!el.hasAttribute(attr)) return;
        var value = el.getAttribute(attr).trim();
        if (!value || !Object.prototype.hasOwnProperty.call(dict, value)) return;
        if (!el.__origAttrs) el.__origAttrs = {};
        if (!(attr in el.__origAttrs)) el.__origAttrs[attr] = el.getAttribute(attr);
        el.setAttribute(attr, dict[value]);
      });
    });
  }

  function toChineseAttrs(root) {
    var els = root.querySelectorAll('[alt],[title]');
    Array.prototype.forEach.call(els, function (el) {
      if (!el.__origAttrs) return;
      Object.keys(el.__origAttrs).forEach(function (attr) {
        el.setAttribute(attr, el.__origAttrs[attr]);
      });
    });
  }

  /* ---------------- 页面标题 ---------------- */
  var origTitle = null;
  function toKoreanTitle() {
    if (origTitle === null) origTitle = document.title;
    var t = document.title.trim();
    if (t && Object.prototype.hasOwnProperty.call(dict, t)) document.title = dict[t];
  }
  function toChineseTitle() {
    if (origTitle !== null) document.title = origTitle;
  }

  /* ---------------- 切换按钮 ---------------- */
  var toggle = null;

  function injectToggle() {
    var host = document.querySelector('.header-content');
    if (!host || document.getElementById('lang-toggle')) return;
    var btn = document.createElement('button');
    btn.type = 'button';
    btn.id = 'lang-toggle';
    btn.className = 'lang-toggle';
    btn.title = '中文 / 한국어';
    btn.addEventListener('click', function () {
      applyLang(current === 'zh' ? 'ko' : 'zh');
    });
    host.appendChild(btn);
    toggle = btn;
    updateToggle();
  }

  function updateToggle() {
    if (toggle) toggle.textContent = (current === 'zh') ? '한국어' : '中文';
  }

  /* ---------------- 应用语言 ---------------- */
  function applyLang(lang) {
    if (lang !== 'ko') lang = 'zh';
    if (lang === current) {
      updateToggle();
      return;
    }
    if (lang === 'ko') {
      toKorean(document.body);
      toKoreanAttrs(document.body);
      toKoreanTitle();
    } else {
      toChinese(document.body);
      toChineseAttrs(document.body);
      toChineseTitle();
    }
    current = lang;
    document.documentElement.setAttribute('lang', lang === 'ko' ? 'ko' : 'zh');
    document.body.setAttribute('data-lang', lang);
    save(lang);
    updateToggle();
  }

  function init() {
    injectToggle();
    applyLang(load() === 'ko' ? 'ko' : 'zh');
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
